// Обращение на «ты» в тексте — для проверки «открытые страницы на „вы“»
// (журнал п.71): test-formal-address.mjs читает файлы, smoke-teacher-path —
// живой текст страниц. Один поиск на обоих, чтобы они не разошлись.

const W = '[а-яё]'
/** Слово целиком: \b в JS кириллицу не видит. */
export const word = (body) => new RegExp(`(?<!${W})(?:${body})(?!${W})`, 'gi')

/** Местоимения, глаголы 2-го лица, повелительное наклонение на «ты». */
const INFORMAL = [
  word('ты|тебя|тебе|тобой|твой|твоя|твоё|твое|твои|твоего|твоей|твоих|твоим|твоими|твоему|твою'),
  word(`${W}+(?:ешь|ёшь|ишь)(?:ся)?`),
  word(
    [
      'проверь', 'введи', 'нажми', 'подожди', 'попробуй', 'открой', 'загляни', 'создай', 'выбери',
      'добавь', 'определи', 'войди', 'придумай', 'впиши', 'напиши', 'присоединяйся', 'зарегистрируйся',
      'скопируй', 'запроси', 'переведи', 'оплати', 'перейди', 'вернись', 'посмотри', 'отправь',
      'укажи', 'обнови', 'начни', 'сохрани', 'повтори', 'назначай', 'проверяй', 'смотри', 'пригласи',
      'подключи', 'заведи', 'продли', 'подтверди', 'отметь', 'напомни', 'реши', 'попроси',
    ].join('|'),
  ),
]

/**
 * Найденные формы на «ты». Короткие названия в «ёлочках» не в счёт: это
 * подписи экранов приложения, а внутри него — «ты» («Пригласи коллегу»,
 * игра «Впиши форму»).
 */
export function informal(text) {
  const plain = text.replace(/«[^«»\n]{1,40}»/g, '«»')
  const out = []
  for (const re of INFORMAL) for (const m of plain.matchAll(re)) out.push(m[0])
  return out
}
