// ============================================================================
// Удалить тестовый аккаунт после проверки — так, чтобы он правда удалился.
//
// Аккаунт удаляется целиком каскадом схемы, со студией репетитора: журнал
// оплат уроков (paid_lessons) только дописывается, но обнуление «кто отметил»
// при удалении аккаунта с миграции 0010 пропускает (до неё удаление такого
// репетитора падало, и аккаунты копились). Держат check-lesson-balance и
// smoke-account (тот же каскад, что у «Удалить аккаунт» в Настройках).
// ============================================================================

/**
 * @param {import('@supabase/supabase-js').SupabaseClient} admin клиент с секретным ключом
 * @param {(q: string) => Promise<unknown>} sql запрос к той же базе (runSql) — уже не нужен, оставлен в подписи 46 вызовов
 * @param {string} id аккаунт
 */
export async function deleteTestUser(admin, sql, id) {
  if (!/^[0-9a-f-]{36}$/.test(id)) throw new Error(`не id аккаунта: ${id}`)
  const { error } = await admin.auth.admin.deleteUser(id)
  // уже удалён (так и проверяли — «Удалить аккаунт») — это не сбой
  if (error && !/user not found/i.test(error.message)) console.log(`  ⚠ аккаунт ${id} не удалился: ${error.message}`)
}
