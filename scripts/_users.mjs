// Удалить тестовый аккаунт после проверки — так, чтобы он правда удалился.
//
// Журнал оплат расписания (paid_lessons, миграция 0009) только дописывается:
// правку строки отклоняет триггер. А ссылка «кто отметил» (created_by) при
// удалении аккаунта обнуляется — это правка, и удаление учителя, который хоть
// раз отметил оплату, падает (500 без подробностей; в базе — «paid_lessons
// только дописывается»). Проверки ловили ошибку `.catch(() => {})`, и
// аккаунты копились (нашлось 04.10.2026, PLAN.md Ф2.7). Удалять строки
// журнала триггер не мешает — сперва они, потом аккаунт. Починка в самой
// базе — пунктом плана (Ф2.15).
// ============================================================================

/**
 * @param {import('@supabase/supabase-js').SupabaseClient} admin клиент с секретным ключом
 * @param {(q: string) => Promise<unknown>} sql запрос к той же базе (runSql)
 * @param {string} id аккаунт
 */
export async function deleteTestUser(admin, sql, id) {
  if (!/^[0-9a-f-]{36}$/.test(id)) throw new Error(`не id аккаунта: ${id}`)
  await sql(`delete from public.paid_lessons where teacher_id = '${id}' or created_by = '${id}'`)
  const { error } = await admin.auth.admin.deleteUser(id)
  if (error) console.log(`  ⚠ аккаунт ${id} не удалился: ${error.message}`)
}
