// Точки перехода по ширине экрана — одно место на JS (журнал п.45–46).
//
//   телефон  < 640 px ≤  планшет  < 1024 px ≤  компьютер
//
// CSS берёт те же числа из tokens.css (--breakpoint-sm / --breakpoint-lg —
// префиксы sm: и lg: в классах). Два места — потому что медиа-запрос в CSS не
// читает переменные; их равенство сверяет scripts/test-tokens.mjs.
// ============================================================================

/** Планшет — от 640 px (sm: в классах). */
export const TABLET_MIN = '40rem'
/** Компьютер — от 1024 px (lg: в классах): меню слева, шторка — боковой панелью. */
export const DESKTOP_MIN = '64rem'

export const TABLET_QUERY = `(min-width: ${TABLET_MIN})`
export const DESKTOP_QUERY = `(min-width: ${DESKTOP_MIN})`
