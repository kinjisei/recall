// ============================================================================
// «AI думает» — подпись с тремя живыми точками.
//
// Зачем. Ожидание ответа модели показывалось статическим текстом в шести
// местах: «печатает…», «Перевожу…», «Разбираю фрагмент…», «Думаю…». Человек
// смотрит в это место дольше, чем в любую карточку (3–8 секунд, а генерация
// материала — до минуты) и не понимает, идёт ли что-то вообще или всё
// зависло. Точки отвечают ровно на этот вопрос.
//
// role="status" — заодно чинит незамеченное: появление статического абзаца
// экранный диктор не объявлял, теперь объявит.
// ============================================================================

export function Thinking({ label, className = '' }: { label: string; className?: string }) {
  return (
    <span
      role="status"
      className={`inline-flex items-center gap-1.5 text-[var(--night-text-40)] ${className}`}
    >
      {label}
      <span aria-hidden className="inline-flex items-end gap-[3px] pb-[3px]">
        {[0, 1, 2].map((i) => (
          <span
            key={i}
            className="dot-bounce inline-block h-[3px] w-[3px] rounded-full bg-current"
            // сдвиг фазы — иначе точки прыгают синхронно и читаются как одна
            style={{ animationDelay: `${i * 160}ms` }}
          />
        ))}
      </span>
    </span>
  )
}
