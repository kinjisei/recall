// ---------------------------------------------------------------------------
// Ширина экрана на компьютере: колонка 640 px или вся страница до 1100 px
// (журнал п.45–46).
//
// Старые экраны на компьютере остаются колонкой 640 px, пока не переедут.
// Общим раскладкам из shared/ui («список + подробности», «колонка чтения»)
// колонки мало — им нужна ширина страницы. Раскладка просит её сама, экран об
// этом не думает: взял раскладку — получил место.
//
// Договор между каркасом и экраном (как focusMode): каркас (app/shell/Layout)
// даёт значение контекста и раздвигает <main>, раскладка включает хуком.
// На телефоне и планшете ничего не меняется — экран и так уже 640 px.
// ---------------------------------------------------------------------------
import { createContext, useContext, useEffect } from 'react'

/** Значение даёт каркас: «экрану нужна ширина страницы — да/нет». */
export const PageWidthContext = createContext<(wide: boolean) => void>(() => {})

/** Просит у каркаса ширину страницы на время жизни компонента. */
export function usePageWidth(wide = true): void {
  const set = useContext(PageWidthContext)
  useEffect(() => {
    set(wide)
    return () => set(false)
  }, [wide, set])
}
