// ---------------------------------------------------------------------------
// Правая панель на компьютере (шторка от 720 px, shared/ui/Sheet) и каркас —
// договор (d0, правило 8; макеты d2, d3-4).
//
// Панель сдвигает содержимое без затемнения, если после сдвига ему хватает
// места (раскладка сказала, сколько ей нужно, — shared/lib/screenWidth):
// неделя сжимается, но остаётся колонками, и с экраном можно сверяться. Не
// хватает — панель ложится поверх с лёгкой дымкой; дымка не закрывает меню
// слева (d3-4).
//
// Каркас (app/shell/Layout) знает геометрию и даёт слот; Sheet спрашивает
// «влезет ли сдвиг», а открывшись со сдвигом — просит каркас отодвинуть
// содержимое. Вне каркаса слота нет: панель всегда поверх, дымка с края окна.
// ---------------------------------------------------------------------------
import { createContext, useContext } from 'react'

export interface SidePanelSlot {
  /** Сдвиг поместится: содержимому после него хватит места своей раскладки. */
  fits: boolean
  /** Где начинается дымка панели поверх: справа от меню (CSS-значение). */
  left: string
  /** Панель со сдвигом открылась / закрылась. */
  setPushed: (on: boolean) => void
}

export const SidePanelContext = createContext<SidePanelSlot | null>(null)

export function useSidePanel(): SidePanelSlot | null {
  return useContext(SidePanelContext)
}
