// ============================================================================
// Куда «наверх» с экранов ученика — зависит от роли (PLAN.md Ф2.18, журнал
// п.70). Ученику «Учёба», «Практика», «Диалог» — вкладки меню, «назад» там
// нет. Учителю это экраны внутри «Моей учёбы»: без «назад» выйти можно было
// только нижним меню, а тест уровня по «На главную» уводил его в расписание.
//
// Договор между каркасом и экраном (как shellInsets): значение по роли и
// адресу даёт каркас (app/shell/Layout, правило — app/navigation), экран
// читает хуком. Экран не импортирует каркас и роль не проверяет сам (§2).
// ============================================================================
import { createContext, useContext } from 'react'

/** Куда вести и подпись кнопки для чтения с экрана. */
export interface UpTarget {
  to: string
  label: string
}

export interface ShellUp {
  /** «Назад» у хаба ученика: null — у этой роли хаб и есть вкладка. */
  tab: UpTarget | null
  /** Главная учёбы: ученику — Главная, учителю — «Моя учёба». */
  home: UpTarget
}

/** Ученик — как было до Ф2.18: хабы без «назад», главная — «/». */
export const STUDENT_UP: ShellUp = { tab: null, home: { to: '/', label: 'На главную' } }

export const ShellUpContext = createContext<ShellUp>(STUDENT_UP)

export function useShellUp(): ShellUp {
  return useContext(ShellUpContext)
}
