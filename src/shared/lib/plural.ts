/**
 * Русское склонение после числа: 1 слово, 2 слова, 5 слов.
 *
 * Жило приватной функцией внутри ReportSheet — а понадобилось и сборке
 * домашки. Второй экземпляр разошёлся бы молча: числительные ошибаются не
 * очевидно («32 новых слов» выглядит почти правильно), и заметить это можно
 * только глазами на конкретном числе.
 */
export function plural(n: number, one: string, few: string, many: string): string {
  const m10 = n % 10
  const m100 = n % 100
  if (m10 === 1 && m100 !== 11) return one
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return few
  return many
}
