// Подписи программы по неделям (PlanView, макет d11-3). Чистый модуль:
// держит test-plan-text.
import type { PlanWeek } from '../../types'

/**
 * Короткое имя недели рядом с «Неделя 1»: AI пишет заголовок «Неделя 1:
 * связки и буксующие слова» — номер уже стоит слева, повторять его незачем.
 * Заголовка нет или он — только номер (старые программы) — фокус недели.
 */
export function weekName(w: PlanWeek): string {
  return w.title.replace(/^\s*неделя\s*\d+\s*[:.—–-]?\s*/i, '').trim() || w.focus
}
