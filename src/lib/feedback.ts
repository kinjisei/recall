// Дырка была не в дизайне: сообщить нам что-либо человек НЕ МОГ вообще —
// ни ученик, ни репетитор. Единственным каналом оставалось «напишет сам»,
// а обычно человек не пишет, а уходит.
//
// Хранение — в уже существующей таблице events через RPC track_event. Это
// сознательно: события пишутся туда же, где воронка, доступ анониму уже открыт
// (значит отзыв можно оставить и с публичного лендинга), новая таблица и новая
// миграция не нужны — сбор работает сразу после деплоя, без действий владельца.
//
// ⚠️ В отличие от аналитики, здесь ошибку НЕ проглатываем. Аналитика может
// молча потерять событие; отзыв — не может: человек потратил минуту, написал
// текст, и обязан узнать, дошло ли.
// ============================================================================
import { supabase } from './supabase'

/** Максимум символов отзыва. Ниже потолка track_event (2 КБ на props). */
export const FEEDBACK_MAX = 900

export interface FeedbackInput {
  /** Общее впечатление. null — человек просто написал, не оценивая. */
  rating: 'up' | 'down' | null
  text: string
  /** Как ответить, если человек хочет ответа. Необязательно. */
  contact?: string
  /** С какого экрана отправлено — по нему видно, что именно обсуждают. */
  where: string
}

export async function sendFeedback(input: FeedbackInput): Promise<void> {
  const text = input.text.trim().slice(0, FEEDBACK_MAX)
  if (!text && !input.rating) throw new Error('Напиши пару слов или поставь оценку.')

  const { error } = await supabase.rpc('track_event', {
    p_name: 'feedback',
    p_props: {
      rating: input.rating,
      text,
      contact: (input.contact ?? '').trim().slice(0, 120) || null,
      where: input.where.slice(0, 60),
      // версия интерфейса помогает понять, о какой сборке речь
      at: new Date().toISOString(),
    } as never,
    p_anon: null,
    p_source: null,
  })
  if (error) throw error
}
