// ============================================================================
// Здоровье AI на стороне клиента: ловим СЕРИЮ серверных сбоёв, чтобы человек не
// бился молча в неработающий AI.
//
// Зачем. Разовый сбой — норма: показали «попробуй ещё раз». Но если AI падает
// раз за разом (выгорела общая квота Google, лёг прокси), человек шлёт снова и
// снова, каждый раз ждёт и злится. После 3 серверных сбоёв за час показываем
// честное «это на нашей стороне, не из-за тебя» и останавливаем обычный поток —
// пусть перепробует осознанно, а не долбит вслепую.
//
// ⚠️ Сетевые сбои (нет интернета) СЮДА НЕ ПИШЕМ: это не сервер, у них своё
// сообщение «проверь интернет». Считаем только ответы-ошибки от сервера.
//
// Хранилище — localStorage: счётчик переживает перезагрузку, но приватен для
// устройства и не стоит серверу ничего. Обёрнуто в try/catch (приватный режим).
// ============================================================================
const KEY = 'recall.aiFails'
const WINDOW_MS = 60 * 60 * 1000 // час
const LIMIT = 3

/** Отметки серверных сбоёв за последний час (старые отсеиваем). */
function recent(): number[] {
  const cutoff = Date.now() - WINDOW_MS
  let times: unknown = []
  try {
    times = JSON.parse(localStorage.getItem(KEY) || '[]')
  } catch {
    times = []
  }
  return Array.isArray(times) ? times.filter((t) => typeof t === 'number' && t > cutoff) : []
}

function save(times: number[]): void {
  try {
    localStorage.setItem(KEY, JSON.stringify(times))
  } catch {
    /* приватный режим или переполнение — не критично */
  }
}

/** Записать СЕРВЕРНЫЙ сбой AI. Сетевые (нет интернета) сюда не передаём. */
export function recordAiServerFailure(): void {
  save([...recent(), Date.now()])
}

/** Успех — забываем прошлые сбои: серия прервана. */
export function clearAiFailures(): void {
  save([])
}

/** Похоже, у AI серия серверных сбоёв — пора остановиться и сказать человеку. */
export function aiOverloaded(): boolean {
  return recent().length >= LIMIT
}
