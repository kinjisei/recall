// ============================================================================
// Куда ведёт пункт домашки. ОДНО место на всё приложение.
//
// ⚠️ Главное правило захода: у одной работы ОДИН способ её сделать. Домашка не
// заводит своих раннеров и своих кнопок «сдать» — она указатель. Пункт «письмо»
// открывает тот же /writing, пункт «квест» — тот же /quests, пункт «задание» —
// тот же раннер на /assignments. Иначе появилось бы два пути закрыть одно и то
// же: сдал через домашку — а на своём экране работа всё ещё «новая».
//
// Из этого же следует, что закрытие пункта нигде не пишется руками: сервер
// закрывает его сам (log_activity + триггеры на таблицах, см. docs/schema.sql).
// Клиент вообще не участвует — он показывает то, что вернул get_homework.
// ============================================================================
import type { HomeworkItem, HomeworkKind } from './homework'

/** Что предлагаем нажать: подпись и адрес. null — идти некуда (галочка). */
export interface HomeworkLink {
  to: string
  label: string
}

/**
 * Куда ведёт пункт. Адреса те же, что у плана дня (lib/dailyPlanCore) — не
 * потому что лень, а потому что это одни и те же экраны: разъехавшись, план
 * дня и домашка отправляли бы ученика в разные места за одним и тем же делом.
 */
const BY_KIND: Record<HomeworkKind, HomeworkLink | null> = {
  words: { to: '/practice', label: 'К словам' },
  text: { to: '/study?view=reader', label: 'К текстам' },
  quest: { to: '/quests', label: 'К квесту' },
  writing: { to: '/writing', label: 'К письму' },
  speech: { to: '/pronunciation', label: 'Проговорить' },
  free: null,
}

/**
 * Ссылка для пункта. Если преподаватель привязал конкретную работу (ref_id),
 * открываем ИМЕННО её, а не список: ученику не нужно угадывать, какое из пяти
 * заданий имелось в виду.
 */
export function homeworkLink(item: HomeworkItem): HomeworkLink | null {
  const base = BY_KIND[item.kind]
  if (!base) return null
  if (!item.ref_id) return base
  if (item.kind === 'text') return { to: `/assignments?a=${item.ref_id}`, label: 'Открыть задание' }
  if (item.kind === 'quest') return { to: `/quests?q=${item.ref_id}`, label: 'К квесту' }
  return base
}

/**
 * Подпись под пунктом: чем он закроется. Ученик должен понимать, что от него
 * ждут, ДО того как откроет экран, — иначе он идёт «куда-то» и возвращается ни
 * с чем.
 *
 * ⚠️ Формулировки честные ровно настолько, насколько честен сервер: «засчитаем
 * по занятиям», а не «проверим». Расписание повторений пишет клиент, и обещать
 * больше нельзя (см. lib/homework.ts).
 */
export const KIND_HINT: Record<HomeworkKind, string> = {
  words: 'Засчитаем по повторённым карточкам',
  text: 'Засчитаем по прочитанному',
  quest: 'Засчитаем, когда квест пройден',
  writing: 'Засчитаем по отправленной работе',
  speech: 'Засчитаем по заходам в тренажёр',
  free: 'Приложение это измерить не может — отметишь сам',
}
