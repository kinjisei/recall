// ============================================================================
// Перевод ВЫДЕЛЕННОЙ ФРАЗЫ/ФРАГМЕНТА целиком (режим «Выделить фразу» в читалке).
// Контекстный словарь (contextDict) заточен под ОДНО слово/идиому и на нескольких
// предложениях обрезает до первого — поэтому у фразы отдельный промпт «переведи
// весь фрагмент по смыслу». Лёгкая модель (task 'word') справляется — проверено
// на проде.
// ============================================================================
import { chat } from './gemini'
import type { AppLang } from '../types'

export async function translatePhrase(text: string, lang: AppLang): Promise<string> {
  const from = lang === 'es' ? 'с испанского' : 'с английского'
  const system = [
    `Переведи фрагмент текста ${from} на русский — точно, естественно и ПО СМЫСЛУ`,
    '(не дословно), сохранив ВСЕ предложения. Верни ТОЛЬКО перевод, без пояснений и кавычек.',
  ].join(' ')
  try {
    const raw = await chat([{ role: 'user', content: text }], { system, task: 'word' })
    return raw
      .trim()
      .replace(/^[«"']+|[»"']+$/g, '')
      .trim()
  } catch {
    return ''
  }
}
