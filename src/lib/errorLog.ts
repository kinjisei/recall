// ============================================================================
// Запись ошибок с прода.
//
// Зачем. Раньше об ошибке у пользователя мы узнавали, только если он напишет —
// а он, скорее всего, просто уйдёт. Перед открытием регистрации для чужих людей
// это значит «выкатываем вслепую».
//
// Почему НЕ внешний сервис (Sentry и подобные). У нас уже работает канал
// событий: таблица events, RLS, защита от накрутки (500/час на устройство),
// поддержка анонимов — ошибке нужно ровно то же самое. Свой канал means: данные
// учеников никуда не уезжают, в политику приватности не добавляется ещё один
// получатель, а смотреть ошибки владелец будет в /admin, куда и так заходит.
// Когда объём вырастет настолько, что разбирать руками станет тяжело, переход
// на внешний сервис — час работы: место вызова одно.
//
// Ограничения, о которых честно: стеков с исходниками не будет (бандл сжат),
// группировки «из коробки» тоже. Для нашего масштаба хватает сообщения, места
// и того, что человек делал.
// ============================================================================
import { track } from './analytics'

/** Сколько ошибок с одного устройства пишем за сессию: одна поломка в цикле
 *  рендера способна выстрелить сотнями одинаковых событий и забить таблицу. */
const MAX_PER_SESSION = 10
let sent = 0

/** Уже отправленные отпечатки — одну и ту же ошибку шлём один раз. */
const seen = new Set<string>()

function short(v: unknown, limit: number): string {
  const s = typeof v === 'string' ? v : v instanceof Error ? v.message : String(v)
  return s.slice(0, limit)
}

/**
 * Записать ошибку. Никогда не бросает и ничего не ждёт: диагностика не имеет
 * права мешать тому, что человек делает.
 *
 * @param where  где случилось — экран или операция («колода», «сдача работы»)
 * @param error  сама ошибка
 */
export function logError(where: string, error: unknown): void {
  try {
    const message = short(error, 300)
    // отпечаток без изменчивых частей (id, время) — иначе одна и та же
    // поломка выглядела бы как сотня разных
    const key = `${where}|${message.replace(/[0-9a-f-]{16,}/gi, '#').slice(0, 120)}`
    if (seen.has(key) || sent >= MAX_PER_SESSION) return
    seen.add(key)
    sent++

    const stack = error instanceof Error ? short(error.stack ?? '', 600) : ''
    void track('client_error', {
      where,
      message,
      // первые строки стека: даже в сжатом виде показывают, какой чанк упал
      stack: stack.split('\n').slice(0, 4).join('\n'),
      path: location.pathname + location.search,
      ua: navigator.userAgent.slice(0, 160),
      // офлайн-ошибки — отдельная история: чинить в коде обычно нечего
      online: navigator.onLine,
    })
  } catch {
    /* запись ошибок сама ошибку не устраивает */
  }
}

/**
 * Глобальные ловушки: необработанные исключения и отклонённые промисы.
 * ErrorBoundary ловит только сбои рендера React — всё, что случается в
 * обработчиках и в async-коде, до сегодняшнего дня не фиксировалось нигде.
 */
export function installErrorLogging(): void {
  window.addEventListener('error', (e) => {
    // ошибки загрузки картинок/скриптов приходят сюда же, но без message
    logError('window', e.error ?? e.message ?? 'unknown')
  })
  window.addEventListener('unhandledrejection', (e) => {
    logError('promise', e.reason ?? 'unknown')
  })
}
