// ============================================================================
// «Плитка выросла в экран» — общий элемент перехода.
//
// Идея из MinimalCarousel (подборка владельца): нажатая карточка не исчезает,
// а разворачивается в то, что открылось. Там это `layoutId` Framer Motion,
// здесь — `view-transition-name` браузера: один и тот же ИМЕНОВАННЫЙ элемент
// в двух кадрах, и переход сам считает, как один превратился в другой.
//
// Как пользоваться:
//   1) в обработчике нажатия: markMorph(e.currentTarget) — до смены состояния;
//   2) на открывшемся экране: useMorphName() и повесить его на заголовок.
//
// ⚠️ Имя ДОЛЖНО быть уникальным в кадре, поэтому оно одно на всё приложение и
// живёт ровно один переход: takeMorphName() его забирает и обнуляет.
//
// ⚠️ Именованный элемент получает layout-containment и становится containing
// block для fixed-потомков. Поэтому помечаем только мелочь без шторок внутри:
// плитку и строку заголовка. Внутрь <main> в целом это вешать нельзя (см.
// комментарий к fade-in в index.css).
// ============================================================================

const NAME = 'recall-morph'

let pending: string | null = null

/** Пометить нажатый элемент источником превращения. */
export function markMorph(el: HTMLElement | null): void {
  if (!el) return
  // если браузер не умеет переходы — просто ничего не делаем
  if (typeof (document as Document & { startViewTransition?: unknown }).startViewTransition !== 'function') return
  el.style.viewTransitionName = NAME
  pending = NAME
  // Страховка: если переход почему-то не случился, имя не должно остаться
  // висеть на элементе — вторым таким же оно сломает следующий переход.
  window.setTimeout(() => {
    el.style.viewTransitionName = ''
  }, 1000)
}

/**
 * Забрать имя для принимающей стороны. Возвращает null, если превращения не
 * было (экран открыли из адресной строки, «назад», deep-link) — тогда играет
 * обычный переход экрана.
 */
export function takeMorphName(): string | null {
  const n = pending
  pending = null
  return n
}
