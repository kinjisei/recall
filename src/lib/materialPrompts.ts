/**
 * Виды упражнений и их правила — один блок на «Новый текст» и «Мой текст»
 * (Ф2.25-1б, журнал п.76 (8)): всё на уровне текста; понимание — без
 * открытых вопросов; «Верно / Неверно» — кнопки на языке текста, у A1–A2
 * без «Не сказано»; словарь — только слова текста (по начальной форме);
 * перевод — на русский, объяснение — на языке текста; грамматика —
 * конструкции текста. Приложение потом приводит ответ к этим правилам
 * (`normalizeExercises`) и выбрасывает то, что им не следует.
 */
export function exerciseSpec(lang: AppLang, level: string): { shapes: string[]; rules: string[] } {
  const L = lang === 'es' ? 'испанском' : 'английском'
  const tf = TFNG_OPTIONS[lang]
  const three = allowsNotGiven(level)
  const tfOpts = JSON.stringify(three ? [...tf] : tf.slice(0, 2))
  return {
    shapes: [
      '    {"kind":"comprehension","type":"mcq","prompt":"вопрос по смыслу на целевом языке","options":["A","B","C","D"],"answer":0},',
      `    {"kind":"comprehension","type":"mcq","format":"tfng","prompt":"утверждение о тексте на ${L}","options":${tfOpts},"answer":1,"quote":"предложение из текста дословно, где это видно","mark":"1-3 слова из quote, на которых держится ответ","why":"по-русски, одно короткое предложение: почему так"},`,
      '    {"kind":"grammar","type":"fill","prompt":"предложение ИЗ текста с пропуском ___","answer":"пропущенная часть","hint":"подсказка по-русски"},',
      '    {"kind":"grammar","type":"mcq","format":"form","prompt":"предложение ИЗ текста с пропуском ___","options":["3-4 формы одного слова"],"answer":0},',
      '    {"kind":"grammar","type":"order","prompt":"перевод предложения по-русски","words":["слова","в","любом","порядке"],"answer":["слова","в","правильном","порядке"]},',
      '    {"kind":"vocab","type":"match","format":"translation","prompt":"Соедини слово и перевод","pairs":[{"left":"слово из текста в начальной форме","right":"перевод на русский"}],"extra":["ещё один перевод на русский — не подходит ни к одному слову"]},',
      `    {"kind":"vocab","type":"match","format":"definition","prompt":"Соедини слово и объяснение","pairs":[{"left":"слово из текста в начальной форме","right":"объяснение на ${L} уровня ${level}, без самого слова"}],"extra":["одно лишнее объяснение того же уровня"]},`,
      '    {"kind":"vocab","type":"mcq","prompt":"определение слова НА ЦЕЛЕВОМ ЯЗЫКЕ (само слово не называть!)","options":["слово1","слово2","слово3","слово4"],"answer":0}',
    ],
    rules: [
      `Всё на уровне текста (${level}): вопросы, утверждения, варианты и объяснения — не сложнее самого текста; ученику ${level} не должно попасться задание уровнем выше.`,
      'Вопросов с открытым ответом нет: понимание текста — только «выбери ответ» (mcq) и «верно / неверно» (mcq с format "tfng").',
      `«Верно / неверно»: options — ровно ${tfOpts} в этом порядке, answer — индекс верной кнопки; ${
        three ? `«${tf[2]}» — только если в тексте об этом нет ничего, тогда quote — пустая строка` : `у текста ${level} третьей кнопки нет`
      }; часть утверждений — неверные: ловушка во внимательности (в тексте сказано иначе), а не в двусмысленности; ответ однозначен по тексту; quote — предложение из текста дословно.`,
      'Словарь — только слова и выражения, которые есть в тексте (в любой форме); в паре и в вариантах пиши начальную форму: «missed her flight» → «miss a flight», «took» → «take». Слово, которого нет в тексте, приложение выбросит.',
      '«Соедини пары» (match): 4-6 пар, слова разные, переводы (объяснения) разные; extra — ровно один лишний вариант того же вида, не подходящий ни к одному слову. Перевод — только на русский; объяснение — на языке текста, без самого слова.',
      'Грамматика — конструкции, которые есть в тексте (тема из заявки — первой). «Выбери форму» (format "form"): 3-4 формы одного слова, верна одна.',
    ],
  }
}

/** Заявка преподавателя (форма создания материала). */
export interface MaterialRequest {
  lang: AppLang
  level: CEFRLevel
  topic: string
  format: string
  lengthRange: MaterialLength
  vocabulary: string
  grammar: string
  /**
   * Для кого (Ф2.11б-3): AI получает диагностику выбранных — то, где они
   * реально ошибаются (без неё генератор — любой чат); «Сохранить» назначает
   * материал им же. Пусто — материал общий.
   */
  studentIds?: string[]
  /** Один ученик: самоучка себе (self) и черновики до Ф2.11б-3. */
  studentId?: string | null
  /**
   * true — ученик собирает материал СЕБЕ (режим самоучки, 3b). Тогда задача
   * уходит как self_material: не teacherOnly, тратит СВОЙ месячный лимит
   * генераций, дешёвая standard-модель. studentId при этом = свой uid (материал
   * подстроится под собственную диагностику).
   */
  self?: boolean
}

