/** Системный промпт «Моего текста»: упражнения строго по готовому тексту преподавателя. */
export function ownTextSystem(
  lang: AppLang,
  level: CEFRLevel,
  compr: string,
  opts?: { vocabulary?: string; grammar?: string; rows?: readonly PlanExercise[] },
): string {
  const langName = lang === 'es' ? 'испанском' : 'английском'
  const spec = exerciseSpec(lang, level)
  const words = (opts?.vocabulary ?? '').split(',').map((w) => w.trim()).filter(Boolean)
  const brief = opts?.rows?.length ? planBrief(opts.rows, { words, grammar: opts.grammar?.trim() ?? '', level }) : []
  return [
    'Ты — автор учебных упражнений по иностранным языкам.',
    `Дан ГОТОВЫЙ текст на ${langName} (уровень ученика — ${level}). Составь упражнения СТРОГО по этому тексту.`,
    'Отвечай ТОЛЬКО валидным JSON без markdown.',
    '',
    'Формат ответа:',
    '{',
    '  "title": "короткий заголовок текста на целевом языке",',
    '  "exercises": [',
    ...spec.shapes,
    '  ]',
    '}',
    '',
    'Жёсткие требования:',
    '1. ВСЕ упражнения строго по содержанию ДАННОГО текста. Не выдумывай фактов, которых в тексте нет.',
    // учитель выбрал виды в заявке (d16-3) — ровно их; иначе — как раньше, на выбор модели
    ...(brief.length
      ? ['2. Упражнения — РОВНО эти виды и столько (других не добавляй, меньше тоже нельзя):', ...brief]
      : [
          `2. Вопросов на понимание (comprehension) — ${compr}: часть mcq, часть «верно / неверно»; грамматических — 3-6 (fill, form и order вперемешку, чтобы задание не было однообразным); словарных (vocab) — 3-6, из них одно «Соедини пары» (match).`,
        ]),
    opts?.grammar?.trim() ? `3. Сделай акцент на грамматике: ${opts.grammar.trim()}.` : '',
    opts?.vocabulary?.trim() ? `4. В словарных упражнениях приоритет словам: ${opts.vocabulary.trim()}.` : '',
    'В fill ответ (answer) — ровно то, что пропущено на месте ___; «/» только для равноправных вариантов (was/were), не как часть самого ответа.',
    'В vocab mcq prompt — простое определение слова уровня ученика БЕЗ самого слова; options — 4 слова (правильное + 3 из текста/того же уровня); answer — индекс правильного. В vocab fill — предложение из текста с ___ на месте слова, answer — слово в форме из текста.',
    'В order: answer — предложение ИЗ текста, разбитое на слова в правильном порядке (3-10 слов); ' +
      'words — РОВНО ТЕ ЖЕ слова (порядок неважен, приложение перемешает); prompt — перевод предложения на русский. ' +
      'Разошёлся состав words и answer — упражнение несобираемое, оно будет выброшено.',
    'Порядок упражнений: сначала comprehension, потом grammar, потом vocab.',
    ...spec.rules,
  ]
    .filter(Boolean)
    .join('\n')
}

/**
 * Замена одного упражнения (Ф2.25-4, журнал п.76 (8), (22)): ровно одно
 * упражнение выбранного вида по готовому тексту — вместо того, что не
 * понравилось учителю, и не похожее на остальные. Правила видов — те же,
 * что у «Нового» и «Моего текста» (`exerciseSpec`, `planBrief`). Ответ
 * сервер пропускает, только если это одно упражнение (`api/_exerciseShape`).
 */
export function swapPrompt(
  lang: AppLang,
  level: string,
  row: PlanExercise,
  ctx: { body: string; words: readonly string[]; grammar: string; replacing: MaterialExercise | null; others: readonly MaterialExercise[] },
): { system: string; user: string } {
  // остальные — коротко: вопрос или предложение, у пар — слова
  const brief = (e: MaterialExercise) => (e.type === 'match' ? `пары: ${e.pairs.map((p) => p.left).join(', ')}` : e.prompt)
  const user = [
    'Текст:',
    ctx.body,
    '',
    ctx.replacing ? `Заменяемое упражнение (новое — другое):\n${JSON.stringify(ctx.replacing)}` : 'Новое упражнение — в дополнение к остальным.',
    ...(ctx.others.length ? ['', 'Остальные упражнения материала (не повторяй):', ...ctx.others.map((e, i) => `${i + 1}. ${brief(e)}`)] : []),
  ].join('\n')
  return { system: swapSystem(lang, level, row, ctx), user }
}

function swapSystem(lang: AppLang, level: string, row: PlanExercise, ctx: { words: readonly string[]; grammar: string }): string {
  const langName = lang === 'es' ? 'испанском' : 'английском'
  const spec = exerciseSpec(lang, level)
  return [
    'Ты — автор учебных упражнений по иностранным языкам.',
    `Дан ГОТОВЫЙ текст на ${langName} (уровень ученика — ${level}) и упражнения к нему. Составь ОДНО новое упражнение СТРОГО по этому тексту: оно заменит упражнение, которое не понравилось преподавателю.`,
    'Отвечай ТОЛЬКО валидным JSON без markdown.',
    '',
    'Формат ответа: {"exercises": [одно упражнение]}, упражнение — по образцу своего вида:',
    ...spec.shapes,
    '',
    'Жёсткие требования:',
    '1. В exercises — РОВНО одно упражнение, и ровно этого вида:',
    ...planBrief([row], { words: ctx.words, grammar: ctx.grammar, level }),
    '2. Строго по содержанию текста: ни одного факта, которого в тексте нет.',
    '3. Не повторяй заменяемое упражнение и остальные упражнения материала: другой вопрос, другое утверждение, другое предложение из текста; у пар — где можно, другие слова.',
    ...spec.rules,
  ].join('\n')
}

/**
 * Системный промпт AI-разбора сданной работы: вердикт и комментарий по
 * каждому упражнению. «Верно то, что верно в языке» (журнал п.74), как у
 * сверки приложения: пропущенная или лишняя буква — ошибка ученика (мягко,
 * «почти»); синоним, верный в предложении, сокращение, регистр, диакритика —
 * верно. Помогают не общие правила, а ЭТАЛОНЫ — тот же приём, что вылечил
 * «Диалог» (lib/correctionRules).
 */
export function reviewSystem(lang: AppLang): string {
  return [
    'Ты — ассистент преподавателя иностранного языка: делаешь ПЕРВИЧНУЮ проверку работы ученика.',
    'Отвечай ТОЛЬКО валидным JSON без markdown:',
    '{"items":[{"index":0,"ok":true,"comment":"..."},{"index":3,"ok":false,"comment":"","pairs":[true,false,true,true]}]}',
    '',
    'Правила:',
    '- comment по-русски, 1-2 предложения;',
    '- если ответ НЕВЕРНЫЙ: объясни, что именно не так, и приведи правильный вариант;',
    '- если ответ верный: пустая строка или короткая похвала;',
    '- ВЕРНО то, что верно в языке, даже если авто-проверка не совпала: синоним, верный в этом предложении (ok=true, в comment — «Верно, в тексте …»), сокращение, другой регистр, диакритика;',
    '- примеры ok=true: «large» вместо «big» (comment: «Верно, в тексте big»), «Went» вместо «went», «don’t» вместо «do not», «I’ve» вместо «I have»;',
    '- НЕВЕРНО слово с пропущенной, лишней или перепутанной буквой — это ошибка ученика: ok=false и мягкий comment «Почти: пишется played»;',
    '- примеры ok=false: «playd» вместо «played», «wich» вместо «which», «freind» вместо «friend»;',
    '- и наоборот: НЕ придумывай ошибку там, где ответ верен. Если сомневаешься, что именно имел в виду ученик, ставь ok=true и напиши сомнение в comment;',
    '- index — как в присланном списке; верни вердикт по КАЖДОМУ упражнению;',
    '- у «Соедини пары» (в упражнении есть pairs: слово, что соединил ученик, верный ответ) верни ещё "pairs":[true,false,…] по порядку — засчитать ли пару: true, если соединено верно или по сути верно (синоним перевода, то же значение); comment у пар — пустая строка.',
    ADDRESS_RULE,
    variantRule(lang),
  ].join('\n')
}
