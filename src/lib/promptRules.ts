// Общие строки для промптов AI — одна копия на все вызовы; что их берут все,
// где нужно, держит scripts/test-ai-prompts.mjs (Ф2.20).
//
// Испанский — Испании (журнал п.74): как уроки и слова приложения (vosotros,
// coche, ordenador, móvil, zumo, piso). Ученик учит одно, а AI подсовывал бы
// другое — путаница, которую новичок не распознает. Латиноамериканское слово
// у самого ученика — не ошибка (язык верный), но AI сам такие не пишет и в
// исправлениях не предлагает.
//
// «Ты» (журнал п.71): внутри приложения к человеку обращаемся на «ты» — и
// ученику, и учителю. Модель по умолчанию пишет «Напишите…»: строка ниже —
// во всех промптах, где AI пишет человеку по-русски.
// ============================================================================

import type { AppLang } from '../types'

export const SPANISH_VARIANT_RULE =
  'Испанский — вариант ИСПАНИИ, как в уроках приложения: vosotros (а не ustedes в значении «вы все»), coche, ordenador, móvil, zumo, piso, conducir, coger. ' +
  'В своих текстах, вопросах, вариантах ответа, исправлениях и примерах НЕ используй латиноамериканские слова и формы (carro, computadora, celular, jugo, departamento, manejar). ' +
  'Если ученик сам написал латиноамериканское слово — это не ошибка: не исправляй, можно лишь подсказать, как скажут в Испании.'

/** Строка для промпта: у испанского — правило варианта, у английского — пусто. */
export function variantRule(lang: AppLang): string {
  return lang === 'es' ? SPANISH_VARIANT_RULE : ''
}

/** Обращение в русском тексте AI — на «ты», как всё приложение внутри. */
export const ADDRESS_RULE = 'По-русски к человеку обращайся на «ты» (напиши, добавь, обрати внимание), как всё приложение, — не на «вы».'
