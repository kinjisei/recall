// ============================================================================
// Сравнение ответов пользователя. Единое правило для всех режимов — иначе
// один и тот же ответ мог считаться верным в игре и неверным в грамматике.
// ============================================================================

/**
 * Нормализация НАПЕЧАТАННОГО ответа перед сравнением. Снимаем всё, что не
 * относится к сути ответа:
 *   регистр                 «Esta» = «esta»
 *   диакритика              «está» = «esta», «ёлка» = «елка»
 *   лишние пробелы          «  Hello  world » = «hello world»
 *   апострофы (любые)       «don't» = «don’t» = «dont»
 *   дефисы и тире → пробел  «well-known» = «well known»
 *   финальная пунктуация    «Yes.» = «Yes»
 *
 * Три последних правила добавлены 2026-08-09 (находка ревью 2А №7): в статике
 * таких ответов нет (0 из 385 fill), но материалы преподавателя пишет AI
 * свободным текстом, и «twenty-one» / «don’t» / точка в конце — вопрос времени.
 *
 * ⚠️ Правило дублируется на сервере: функция norm_typed в docs/schema.sql
 * (блок «НОРМАЛИЗАЦИЯ ПЕЧАТНОГО ОТВЕТА»). Меняешь тут — меняй и там, иначе
 * клиент покажет «верно», а серверный пересчёт балла не засчитает.
 *
 * Чего сознательно НЕ делаем: не склеиваем дефис в ноль символов («e-mail» ≠
 * «email») и не трогаем внутреннюю пунктуацию — иначе размывались бы реальные
 * различия вроде «into» / «in to».
 */
export function normalizeAnswer(s: string): string {
  const raw = s.trim().toLowerCase()
  if (!raw) return ''
  const base = raw
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '') // диакритические знаки
    .replace(/['‘’ʼ´`]/g, '') // апострофы всех начертаний
    .replace(/[-‐‑‒–—]/g, ' ') // дефисы и тире
    .replace(/\s+/g, ' ')
    .trim()
  const trimmed = base.replace(/[.!?,;:…]+$/, '').trim()
  // Непустой ответ НИКОГДА не должен схлопнуться в пустую строку: иначе ответ
  // «-» или «’» сравнялся бы с пустым полем и засчитался бы ни за что.
  // Поэтому откатываемся к предыдущей форме, а в пределе — к исходной.
  return trimmed || base || raw
}

/**
 * Проверка ответа с поддержкой вариантов через «/»: answer «was/were»
 * принимает и «was», и «were». Каждый вариант сравнивается нормализованно.
 * Серверный пересчёт балла заданий (submit_material в schema.sql) обязан
 * считать так же — при изменении правила менять оба места.
 *
 * Только для НАПЕЧАТАННЫХ ответов (fill, order, перепроверка слов, диктант,
 * неправильные глаголы). Для mcq сверка идёт по индексу выбранного варианта —
 * там мягкая нормализация не нужна и вредна (два варианта ответа, отличающиеся
 * только апострофом, — «It's» / «Its» — обязаны остаться разными).
 */
export function answerMatches(given: string, expected: string): boolean {
  const g = normalizeAnswer(given)
  return expected.split('/').some((variant) => normalizeAnswer(variant) === g)
}
