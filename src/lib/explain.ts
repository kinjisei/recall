// ============================================================================
// «Почему?» в разборе результатов практики: короткое объяснение ошибки от AI
// по запросу (дешёвая модель, task 'word'). Кэш в памяти на сессию — повторный
// тап по тому же вопросу не тратит лимит.
// ============================================================================
import { chat } from './gemini'
import type { AppLang } from '../types'

const cache = new Map<string, string>()

export async function explainMistake(
  prompt: string,
  given: string,
  correct: string,
  lang: AppLang,
): Promise<string> {
  const key = `${lang}|${prompt}|${given}|${correct}`
  const hit = cache.get(key)
  if (hit) return hit

  const langName = lang === 'es' ? 'испанский' : 'английский'
  const system = [
    `Ученик учит ${langName} язык и ошибся в упражнении. Объясни ПРИЧИНУ ошибки по-русски, коротко (2-3 предложения) и просто, как школьнику.`,
    '— Слово или перевод: скажи, что на самом деле значит вариант ученика и что значит верный, в чём разница по смыслу.',
    '— Если варианты отличаются только написанием одного слова (опечатка): НЕ выдумывай «два разных слова» — это одно слово, просто верное написание такое-то; можешь дать подсказку, как запомнить.',
    '— Устойчивое выражение или фразовый глагол: НЕ разбирай слова по отдельности буквально — скажи, что это устойчивая фраза и что она целиком значит.',
    '— Грамматика: назови простое правило, из-за которого нужен верный вариант.',
    'НЕ пересказывай задание и НЕ пиши «верно, потому что верно». Дай именно причину. Без лингвистических терминов, без кавычек.',
  ].join(' ')
  const user = `Вопрос: «${prompt}»\nОтвет ученика: «${given}»\nВерный ответ: «${correct}»`
  const raw = await chat([{ role: 'user', content: user }], { system, task: 'word' })
  const text = raw.trim()
  if (cache.size >= 200) cache.delete(cache.keys().next().value as string)
  cache.set(key, text)
  return text
}
