// ============================================================================
// Прокрутка вкладки запоминается (лист s4, «Переключение вкладки»): ушёл из
// «Учёбы» с середины списка в «Практику» и вернулся вкладкой — список там же,
// где был. Остальные переходы (внутрь экрана, «назад») по-прежнему начинают
// сверху — ScrollToTop.
//
// Договор: панель вкладок (useNavTabs) перед переходом запоминает прокрутку
// своего адреса и говорит, куда ведёт вкладка; ScrollToTop на новом адресе
// спрашивает, вернуть ли прокрутку.
// ============================================================================

const saved = new Map<string, number>()
let pending: string | null = null

/** Нажата вкладка: запомнить, где стояли, и ждать перехода на `to`. */
export function leaveByTab(from: string, to: string): void {
  saved.set(from, window.scrollY)
  pending = to
}

/** Куда прокрутить новый адрес: запомненное место, если пришли вкладкой. */
export function tabScrollFor(pathname: string): number | null {
  const byTab = pending === pathname
  pending = null
  return byTab ? (saved.get(pathname) ?? null) : null
}
